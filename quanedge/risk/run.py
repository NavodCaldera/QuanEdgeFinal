"""
The risk workstream in one command:

    python -m quanedge.risk.run            # full run: 500 bootstrap resamples + rolling forecasts
    python -m quanedge.risk.run --quick    # 50 resamples, no rolling forecasts (a fast look)

Writes results/risk/tables/*.csv, results/risk/figures/*.png and
results/risk/summary.md.  Every sentence in the summary is computed from the
tables, so the write-up cannot drift from the numbers.  Inputs are the
TEMPORARY development data and placeholder equal weights until Persons 1 and
2 deliver (see settings.py).
"""
import argparse
import time
from datetime import date

import pandas as pd

from ..config import CONF_LEVELS, PORTFOLIO_VALUE, RESULTS_DIR
from . import dev_data, diagnostics, plots, rolling, settings as S
from .evt import select_threshold
from .models import LABEL, UNCONDITIONAL, fit_models, risk_table
from .portfolio import loss_fraction, portfolio_log_returns
from .uncertainty import bootstrap_intervals, with_intervals
from .var_es import batch_se

OUT = RESULTS_DIR / "risk"


def _k(usd: float) -> str:
    return f"${usd / 1e3:,.0f}k"


def _pct(log_loss: float) -> str:
    return f"{100 * loss_fraction(log_loss):.2f}%"


def _versus(a: float, b: float) -> str:
    """'21% below' / '8% above': a relative to b."""
    d = 100 * (1 - a / b)
    return f"{abs(d):.0f}% {'below' if d > 0 else 'above'}"


def _md_table(df: pd.DataFrame) -> list[str]:
    rows = ["| " + " | ".join(map(str, df.columns)) + " |", "|" + "---|" * df.shape[1]]
    return rows + ["| " + " | ".join(map(str, r)) + " |" for r in df.itertuples(index=False)]


def summary(r, models, table, checks, inside, mc_err, bs, reps) -> str:
    d = diagnostics.describe(r)
    t = table.set_index(["method", "alpha"])
    ev, sc = models["evt"], models["evt"].scan
    chosen, stable = select_threshold(sc), sc[sc["stable"]]
    h, n, e = t.loc[("historical", 0.99)], t.loc[("normal", 0.99)], t.loc[("evt", 0.99)]
    L = [
        "# Risk measurement summary (Person 3)", "",
        f"Generated by `python -m quanedge.risk.run` on {date.today():%d %b %Y}. "
        "Every number is read from `results/risk/tables/`.", "",
        "> **Placeholder inputs.** Development data (yfinance adjusted closes) and **equal weights** stand in "
        "for Person 1's cleaned dataset and Person 2's recommended portfolio. Every number here will change "
        "when those land.", "",
        "## Data", "",
        f"- {d['n_days']:,} trading days, {d['start']:%d %b %Y} to {d['end']:%d %b %Y}. Weights: "
        + ", ".join(f"{k} {v:.1%}" for k, v in S.DEV_WEIGHTS.items()) + ".",
        f"- Daily volatility {100 * d['vol_daily']:.2f}% ({100 * d['vol_annual']:.1f}% annualised); skewness "
        f"{d['skewness']:.2f}; excess kurtosis {d['excess_kurtosis']:.1f} (normal: 0).",
        f"- Worst day {d['worst_day_date']:%d %b %Y}: {_pct(-d['worst_day'])} "
        f"(${PORTFOLIO_VALUE * loss_fraction(-d['worst_day']):,.0f}).", "",
        f"## One-day VaR and ES on USD {PORTFOLIO_VALUE / 1e6:.0f}m", "",
        f"Brackets: 95% interval from {reps} moving-block bootstrap resamples (unconditional models). "
        "The 90% level is in `risk_table.csv`.", "",
        "| Model | 95% VaR | 95% ES | 99% VaR | 99% ES |", "|---|---|---|---|---|",
    ]
    for m in models:
        cells = []
        for a in (0.95, 0.99):
            row = t.loc[(m, a)]
            for q in ("var", "es"):
                c = _k(row[f"{q}_usd"])
                if pd.notna(row[f"{q}_lo_usd"]):
                    c += f" [{_k(row[f'{q}_lo_usd'])}–{_k(row[f'{q}_hi_usd'])}]"
                cells.append(c)
        L.append(f"| {LABEL[m]} | " + " | ".join(cells) + " |")

    u99 = table[(table["alpha"] == 0.99) & table["method"].isin(UNCONDITIONAL)]
    lo, hi = u99.loc[u99["var_usd"].idxmin()], u99.loc[u99["var_usd"].idxmax()]
    t_low = [a for a in CONF_LEVELS if t.loc[("student_t", a), "var"] < t.loc[("normal", a), "var"]]
    mc_gap = max(abs(t.loc[("mc_normal", a), "var_usd"] - t.loc[("normal", a), "var_usd"]) for a in CONF_LEVELS)
    mc_se = PORTFOLIO_VALUE * mc_err.loc[mc_err["method"] == "mc_normal", "var_se"].max()
    mcn, mct = t.loc[("mc_normal", 0.99)], t.loc[("mc_t", 0.99)]
    g, f = models["garch_evt"], t.loc[("fhs", 0.99)]
    L += [
        "", "## Where the models disagree (99%, one day)", "",
        f"- Unconditional 99% VaR runs from {_k(lo['var_usd'])} ({lo['label']}) to {_k(hi['var_usd'])} "
        f"({hi['label']}), a ratio of {hi['var_usd'] / lo['var_usd']:.2f}.",
        f"- Normal 99% VaR is {_versus(n['var_usd'], h['var_usd'])} historical simulation; normal 99% ES is "
        f"{_versus(n['es_usd'], h['es_usd'])}.",
        f"- ES/VaR at 99%: normal {n['es_over_var']:.2f} (fixed by the bell shape), historical "
        f"{h['es_over_var']:.2f}, EVT {e['es_over_var']:.2f}. The larger the ratio, the deeper the tail beyond VaR.",
    ]
    if t_low:
        L.append(f"- Student-t VaR is below normal VaR at {', '.join(f'{a:.0%}' for a in t_low)}: the t puts more "
                 "weight in the centre, so its fat tail only bites further out.")
    L += [
        f"- Monte Carlo (normal) is within {_k(mc_gap)} of parametric normal at every level (simulation standard "
        f"error about {_k(mc_se)}): the same assumption gives the same answer.",
        f"- Monte Carlo (Student-t) adds joint fat tails (ν = {models['mc_t'].params['nu']:.1f}): 99% ES "
        f"{_k(mct['es_usd'])} against {_k(mcn['es_usd'])} under the multivariate normal.",
        f"- Tomorrow's GARCH volatility forecast is {100 * g.filter.sigma_next:.2f}% a day against "
        f"{100 * d['vol_daily']:.2f}% on average, so conditional 99% VaR is {_k(t.loc[('garch_evt', 0.99), 'var_usd'])} "
        f"(GARCH-EVT) and {_k(f['var_usd'])} (FHS) against {_k(h['var_usd'])} unconditional.",
        "", "## EVT", "",
        f"- Threshold rule (lowest KS distance among stable thresholds with at least {S.EVT_MIN_EXCEED} "
        f"exceedances): the {100 * chosen['q']:.1f}th percentile of daily losses, u = {100 * chosen['u']:.2f}%, "
        f"{int(chosen['n_exceed'])} exceedances.",
        f"- Tail index ξ = {ev.params['xi']:.3f} (s.e. {ev.params['xi_se']:.3f}). "
        + ("ξ > 0: a power-law tail. " if ev.params["xi"] > 0 else "")
        + ("ξ < 0.5: finite variance. " if ev.params["xi"] < 0.5 else "")
        + ("ξ < 1: ES exists." if ev.params["xi"] < 1 else "ξ ≥ 1: ES is infinite."),
        f"- ξ is stable from the {100 * stable['q'].min():.1f}th percentile up. Across all stable thresholds, "
        f"99% VaR stays within {_pct(stable['var_0.99'].min())}–{_pct(stable['var_0.99'].max())} and 99% ES within "
        f"{_pct(stable['es_0.99'].min())}–{_pct(stable['es_0.99'].max())}.",
        f"- At 99.9% (about one day in four years): EVT VaR {_pct(ev.var(0.999))}, historical "
        f"{_pct(models['historical'].var(0.999))}, normal {_pct(models['normal'].var(0.999))}.",
        f"- After the GARCH filter the residual tail index is ξ = {g.params['z_xi']:.3f} "
        f"(s.e. {g.params['z_xi_se']:.3f}), against {ev.params['xi']:.3f} for raw returns.",
        "", "## Assumption checks", "",
    ]
    c = checks.assign(statistic=checks["statistic"].map("{:,.2f}".format),
                      p_value=checks["p_value"].map(lambda p: "<0.0001" if p < 1e-4 else f"{p:.4f}"))
    L += _md_table(c[["assumption", "test", "statistic", "p_value", "supported"]])
    i99 = inside[inside["alpha"] == 0.99]
    L += ["", "## In-sample breach rate of the full-sample 99% VaR (a fit check, not a backtest)", ""]
    L += _md_table(pd.DataFrame({"model": i99["method"].map(LABEL), "breaches": i99["breaches"],
                                 "breach rate": i99["breach_pct"].map("{:.2f}%".format), "expected": "1.00%"}))
    L += ["", "## Rolling out-of-sample breaches (raw counts; formal tests are Person 4's)", ""]
    if bs is None:
        L.append("Skipped (`--quick`).")
    else:
        p = bs.pivot(index="method", columns="alpha", values="breaches")
        exp = bs.groupby("alpha")["expected_breaches"].first()
        L.append(f"{int(bs['days'].iloc[0]):,} forecast days; window {S.ROLL_WINDOW} days, slow models refitted "
                 f"every {S.ROLL_REFIT} days.")
        L.append("")
        L += _md_table(pd.DataFrame({"model": [LABEL[m] for m in p.index],
                                     **{f"{a:.0%} breaches (expected {exp[a]:.0f})": p[a].to_numpy()
                                        for a in p.columns}}))
    L += ["", "## Files", "",
          "`tables/`: risk_table, evt_threshold_scan, assumption_checks, worst_days, in_sample_breaches, "
          "model_parameters, mc_simulation_error, rolling_forecasts, rolling_breaches. "
          "`figures/`: fig1–fig7.", ""]
    return "\n".join(L)


def main(argv=None):
    ap = argparse.ArgumentParser(description="Person 3: VaR, ES and EVT for the portfolio")
    ap.add_argument("--quick", action="store_true", help="50 bootstrap resamples, no rolling forecasts")
    ap.add_argument("--refresh-data", action="store_true", help="re-download prices instead of using the cache")
    args = ap.parse_args(argv)
    t0 = time.time()
    tab_dir, fig_dir = OUT / "tables", OUT / "figures"
    tab_dir.mkdir(parents=True, exist_ok=True)
    fig_dir.mkdir(parents=True, exist_ok=True)

    x = dev_data.load_log_returns(args.refresh_data)
    w = S.DEV_WEIGHTS
    r = portfolio_log_returns(x, w)
    models = fit_models(x, w)
    ev = models["evt"]
    print(f"[{time.time() - t0:5.0f}s] fitted {len(models)} models on {len(r):,} days")

    reps = 50 if args.quick else S.BOOT_REPS
    ci = bootstrap_intervals(x, w, reps=reps, evt_threshold_q=ev.params["threshold_q"])
    table = with_intervals(risk_table(models), ci)
    print(f"[{time.time() - t0:5.0f}s] bootstrap intervals ({reps} resamples)")

    checks = diagnostics.assumption_checks(r, z=models["fhs"].filter.z)
    inside = diagnostics.in_sample_breaches(r, {m: models[m] for m in UNCONDITIONAL}, CONF_LEVELS)
    params = pd.DataFrame([(m, k, v) for m, mod in models.items() for k, v in mod.params.items()],
                          columns=["method", "parameter", "value"])
    mc_err = pd.DataFrame([(m, a, *batch_se(models[m], a)) for m in ("mc_normal", "mc_t") for a in CONF_LEVELS],
                          columns=["method", "alpha", "var_se", "es_se"])
    outputs = {"risk_table": table, "evt_threshold_scan": ev.scan, "assumption_checks": checks,
               "worst_days": diagnostics.worst_days(r, x), "in_sample_breaches": inside,
               "model_parameters": params, "mc_simulation_error": mc_err}

    fc = bs = None
    if not args.quick:
        fc = rolling.rolling_forecasts(r)
        bs = rolling.breach_summary(fc)
        outputs["rolling_breaches"] = bs
        fc.to_csv(tab_dir / "rolling_forecasts.csv", float_format="%.6g")
        print(f"[{time.time() - t0:5.0f}s] rolling forecasts ({len(fc):,} days)")
    for name, df in outputs.items():
        df.to_csv(tab_dir / f"{name}.csv", index=False, float_format="%.6g")

    figures = {
        "fig1_distribution": plots.fig_distribution(r, models),
        "fig2_evt_threshold": plots.fig_threshold(ev.scan, select_threshold(ev.scan)["q"]),
        "fig3_evt_tail_fit": plots.fig_evt_fit(ev, models["normal"]),
        "fig4_var_es_comparison": plots.fig_comparison(table),
        "fig5_var_by_confidence": plots.fig_tail_curve(models),
        "fig6_estimate_uncertainty": plots.fig_uncertainty(table),
    }
    if fc is not None:
        figures["fig7_rolling_var"] = plots.fig_rolling(fc)
    for name, fig in figures.items():
        fig.savefig(fig_dir / f"{name}.png")

    (OUT / "summary.md").write_text(summary(r, models, table, checks, inside, mc_err, bs, reps), encoding="utf-8")
    print(f"[{time.time() - t0:5.0f}s] wrote {OUT}")


if __name__ == "__main__":
    main()
